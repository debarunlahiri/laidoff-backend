CREATE TABLE api_request_logs (
    id CHAR(36) NOT NULL PRIMARY KEY,
    request_id CHAR(36) NOT NULL,
    actor_user_id CHAR(36) NULL,
    http_method VARCHAR(16) NOT NULL,
    request_path VARCHAR(2048) NOT NULL,
    route_pattern VARCHAR(512) NULL,
    request_query JSON NULL,
    request_headers JSON NULL,
    request_body JSON NULL,
    response_headers JSON NULL,
    response_body JSON NULL,
    http_status_code SMALLINT UNSIGNED NOT NULL,
    response_size_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
    request_size_bytes BIGINT UNSIGNED NULL,
    duration_milliseconds DECIMAL(14,3) NOT NULL,
    client_ip_address VARCHAR(45) NULL,
    client_user_agent VARCHAR(1024) NULL,
    response_completed BOOLEAN NOT NULL,
    started_at DATETIME(3) NOT NULL,
    completed_at DATETIME(3) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY uq_api_request_logs_request_id (request_id),
    INDEX idx_api_logs_user_started (actor_user_id, started_at),
    INDEX idx_api_logs_status_started (http_status_code, started_at),
    INDEX idx_api_logs_started (started_at)
) ENGINE=InnoDB;

CREATE TABLE application_logs (
    id CHAR(36) NOT NULL PRIMARY KEY,
    request_id CHAR(36) NULL,
    actor_user_id CHAR(36) NULL,
    log_level ENUM('debug', 'info', 'warn', 'error', 'fatal') NOT NULL,
    event_name VARCHAR(160) NOT NULL,
    log_message TEXT NOT NULL,
    log_context JSON NULL,
    error_name VARCHAR(160) NULL,
    error_code VARCHAR(160) NULL,
    error_stack_trace MEDIUMTEXT NULL,
    process_identifier INT UNSIGNED NOT NULL,
    host_name VARCHAR(255) NOT NULL,
    occurred_at DATETIME(3) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX idx_application_logs_request (request_id),
    INDEX idx_application_logs_level_time (log_level, occurred_at),
    INDEX idx_application_logs_event_time (event_name, occurred_at)
) ENGINE=InnoDB;

CREATE TABLE database_query_logs (
    id CHAR(36) NOT NULL PRIMARY KEY,
    request_id CHAR(36) NULL,
    actor_user_id CHAR(36) NULL,
    database_name VARCHAR(128) NOT NULL,
    sql_operation VARCHAR(32) NOT NULL,
    sql_statement_template MEDIUMTEXT NOT NULL,
    parameter_count INT UNSIGNED NOT NULL,
    parameter_types JSON NULL,
    affected_row_count BIGINT UNSIGNED NULL,
    returned_row_count BIGINT UNSIGNED NULL,
    duration_milliseconds DECIMAL(14,3) NOT NULL,
    was_successful BOOLEAN NOT NULL,
    error_code VARCHAR(160) NULL,
    error_message TEXT NULL,
    transaction_id CHAR(36) NULL,
    started_at DATETIME(3) NOT NULL,
    completed_at DATETIME(3) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX idx_database_logs_request (request_id),
    INDEX idx_database_logs_success_started (was_successful, started_at),
    INDEX idx_database_logs_transaction (transaction_id)
) ENGINE=InnoDB;

CREATE TABLE audit_logs (
    id CHAR(36) NOT NULL PRIMARY KEY,
    request_id CHAR(36) NULL,
    actor_user_id CHAR(36) NULL,
    action_name VARCHAR(160) NOT NULL,
    resource_type VARCHAR(100) NOT NULL,
    resource_identifier VARCHAR(160) NULL,
    outcome ENUM('succeeded', 'rejected', 'failed') NOT NULL,
    change_summary JSON NULL,
    client_ip_address VARCHAR(45) NULL,
    occurred_at DATETIME(3) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX idx_audit_logs_actor_time (actor_user_id, occurred_at),
    INDEX idx_audit_logs_resource (resource_type, resource_identifier),
    INDEX idx_audit_logs_request (request_id)
) ENGINE=InnoDB;
